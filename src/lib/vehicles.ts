export const tyreRadiusM = (vehicle: Vehicle) => {
  const match = /(\d{3})\/(\d{2})R?(\d{2})/.exec(vehicle.chassis.tyre.replace("R", ""));
  if (match) {
    const width = Number(match[1]) / 1000;
    const aspect = Number(match[2]) / 100;
    const rim = Number(match[3]) * 0.0254;
    return rim / 2 + width * aspect;
  }
  return (vehicle.chassis.wheelDiameterIn * 0.0254) / 2 + 0.1;
};

