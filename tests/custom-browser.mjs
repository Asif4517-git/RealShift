// Isolated mobile-browser editor and photo checks; no user storage is modified.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl']});
const page=await browser.newPage({viewport:{width:390,height:844}}); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(process.env.BASE_URL||'http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Garage',exact:true}).first().click();
  await page.getByLabel('Build name').fill('Diesel test');
  await page.locator('label').filter({hasText:'Fuel'}).locator('select').selectOption('Diesel');
  await page.locator('label').filter({hasText:'Induction'}).locator('select').selectOption('Turbo');
  await page.locator('label').filter({hasText:'Layout'}).locator('select').selectOption('Inline');
  await page.getByLabel('Cylinders',{exact:true}).fill('4');
  await page.getByLabel('Displacement (cc)').fill('2800');
  await page.getByLabel('Power target (hp)').fill('180');
  await page.getByLabel('Peak torque (Nm)').fill('420');
  await page.getByLabel('Idle (rpm)').fill('800');
  await page.getByLabel('Redline (rpm)').fill('4500');
  await page.getByLabel('Limiter (rpm)').fill('4700');
  await page.getByLabel('Flywheel inertia (kg·m²)').fill('0.35');
  await page.getByLabel('Reverse ratio').fill('3.8');
  await page.getByLabel('Final drive').fill('3.9');
  await page.getByLabel('Clutch capacity (Nm)').fill('600');
  await page.locator('label').filter({hasText:'Drivetrain'}).locator('select').selectOption('4WD');
  await page.getByLabel('Mass (kg)').fill('2100');
  await page.getByLabel('Tyre (determines radius)').fill('265/65R17');
  await page.getByLabel('Top-speed target (km/h)').fill('170');
  await page.locator('label').filter({hasText:'Clutch mode (app setting)'}).locator('select').selectOption('manual');
  await page.getByLabel('Forward gears for automatic ratios').fill('5');
  await page.getByRole('button',{name:'Generate ratios'}).click();
  await page.getByRole('button',{name:'Save build',exact:true}).click();
  await page.getByText('Build saved and selected.').waitFor();
  let builds=await page.evaluate(()=>JSON.parse(localStorage.getItem('realshift.custom.v1')));
  assert.equal(builds.length,1); assert.equal(builds[0].spec.fuel,'Diesel'); assert.equal(builds[0].spec.ratios.length,5); assert.equal(builds[0].spec.drivetrain,'4WD');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Garage',exact:true}).first().click();
  await page.getByRole('button',{name:'Duplicate'}).click();
  assert.equal(await page.getByLabel('Build name').inputValue(),'Diesel test copy');
  await page.getByRole('button',{name:'Save build',exact:true}).click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('realshift.custom.v1')).length===2);
  page.once('dialog',d=>d.dismiss()); await page.getByRole('button',{name:'Delete',exact:true}).last().click();
  assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('realshift.custom.v1')))).length,2);
  page.once('dialog',d=>d.accept()); await page.getByRole('button',{name:'Delete',exact:true}).last().click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('realshift.custom.v1')).length===1);
  page.once('dialog',d=>d.accept()); await page.getByRole('button',{name:'Restore editor defaults'}).click();
  assert.equal(await page.getByLabel('Build name').inputValue(),'My build');
  const dims=await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth,photos:[...document.querySelectorAll('img')].filter(x=>x.alt.includes('representative')).map(x=>({alt:x.alt,ok:x.complete&&x.naturalWidth>0}))}));
  assert.equal(dims.scroll,dims.width,'mobile document must not overflow horizontally'); assert(dims.photos.length===13 && dims.photos.every(p=>p.ok));
  assert.deepEqual(errors,[]); console.log(`Mobile editor create, persistence, duplicate, cancel/delete, defaults and ${dims.photos.length} photo loads passed.`);
} finally { await browser.close(); }
